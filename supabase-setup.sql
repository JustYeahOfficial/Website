-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  message text not null check (char_length(message) between 1 and 1000),
  archived boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.public_replies (
  id bigint generated by default as identity primary key,
  message_id bigint references public.contact_messages(id) on delete set null,
  name text not null,
  reply text not null,
  created_at timestamptz not null default now()
);
alter table public.contact_messages enable row level security;
alter table public.public_replies enable row level security;
-- Visitors may submit messages. Only authenticated admins can read/archive them.
create policy "Anyone can send contact messages" on public.contact_messages
for insert to anon, authenticated with check (true);
create policy "Admins can read messages" on public.contact_messages
for select to authenticated using (true);
create policy "Admins can archive messages" on public.contact_messages
for update to authenticated using (true) with check (true);
-- Public replies are readable by everyone; only signed-in admins can publish.
create policy "Anyone can read public replies" on public.public_replies
for select to anon, authenticated using (true);
create policy "Admins can publish replies" on public.public_replies
for insert to authenticated with check (true);
-- IMPORTANT: create your admin user in Supabase Authentication > Users.
-- For production, tighten authenticated policies to an explicit admin allowlist/role.
